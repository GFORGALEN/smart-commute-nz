export const messages = { en, 'zh-CN': zh };
export type MessageKey = keyof typeof en;
export function createTranslator(locale: Locale = 'en') {
  return (key: MessageKey, params: Record<string, string | number> = {}): string => {
    let message: string = messages[locale][key];
    for (const [name, value] of Object.entries(params))
      message = message.replaceAll(`{${name}}`, String(value));
    return message;
  };
}

export function formatMoney(value: number, locale: Locale = 'en'): string {
  return new Intl.NumberFormat(locale === 'zh-CN' ? 'zh-CN' : 'en-NZ', {
    style: 'currency',
    currency: 'NZD',
    currencyDisplay: 'narrowSymbol',
  }).format(value);
}
